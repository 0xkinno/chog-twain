// Regenerates contracts/test/GazeProofCompat.t.sol from OUR OWN data/gaze.json, so the JavaScript tree builder
// and the Solidity verifier are proven to agree on the data we actually ship.
// Usage: node scripts/gen-compat-test.mjs
import { readFileSync, writeFileSync } from "node:fs";

const g = JSON.parse(readFileSync("data/gaze.json", "utf8"));
const ids = Object.keys(g.proofs);
const pick = (side) => ids.find((id) => g.proofs[id].side === side);
const cases = [
  { id: pick(2), name: "right" },
  { id: pick(1), name: "left" },
  { id: pick(3), name: "front" },
];
const wrongId = ids.find((id) => g.proofs[id].side === 2 && id !== cases[0].id);

const proofLit = (name, proof) =>
  `        bytes32[] memory ${name} = new bytes32[](${proof.length});\n` +
  proof.map((h, i) => `        ${name}[${i}] = ${h};`).join("\n");

let body = "";
for (const c of cases) {
  const p = g.proofs[c.id];
  body += `
    function test_jsProofVerifiesOnChain_${c.name}() public {
        ChogTwain t = _twain();
${proofLit("p", p.proof)}
        t.proveGaze(${c.id}, ${p.side}, p);
        assertEq(t.gazeOf(${c.id}), ${p.side});
    }
`;
}
const first = g.proofs[cases[0].id];
body += `
    function test_proofForAnotherTokenOrGazeReverts() public {
        ChogTwain t = _twain();
${proofLit("p", first.proof)}
        vm.expectRevert(ChogTwain.BadProof.selector);
        t.proveGaze(${wrongId}, 2, p); // right proof, wrong token
        vm.expectRevert(ChogTwain.BadProof.selector);
        t.proveGaze(${cases[0].id}, 1, p); // right token, forged gaze
    }
`;

const out = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

import {Test} from "forge-std/Test.sol";
import {ChogTwain} from "../src/ChogTwain.sol";

/// @dev GENERATED by scripts/gen-compat-test.mjs from data/gaze.json. Do not edit by hand.
///      Cross-checks the JavaScript tree builder (scripts/build-gaze.mjs) against the Solidity verifier,
///      for a Right, a Left and a Front (1:1) Chog, and for forged proofs.
contract GazeProofCompatTest is Test {
    bytes32 constant ROOT = ${g.root};

    function _twain() internal returns (ChogTwain) {
        return new ChogTwain(address(1), address(2), ROOT, 1, block.timestamp);
    }
${body}}
`;
writeFileSync("contracts/test/GazeProofCompat.t.sol", out);
console.log(`wrote GazeProofCompat.t.sol for tokens ${cases.map((c) => c.id).join(", ")} (root ${g.root})`);
